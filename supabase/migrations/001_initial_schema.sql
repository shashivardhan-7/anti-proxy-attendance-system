-- Anti-Proxy Attendance MVP
-- Initial database schema

create extension if not exists pgcrypto;

-- =========================================================
-- ENUMS
-- =========================================================

do $$
begin
    if not exists (select 1 from pg_type where typname = 'user_role') then
        create type user_role as enum ('admin', 'professor', 'student');
    end if;

    if not exists (select 1 from pg_type where typname = 'session_status') then
        create type session_status as enum ('active', 'closed');
    end if;

    if not exists (select 1 from pg_type where typname = 'device_status') then
        create type device_status as enum ('active', 'revoked');
    end if;

    if not exists (select 1 from pg_type where typname = 'attendance_status') then
        create type attendance_status as enum ('verified', 'rejected');
    end if;
end $$;


-- =========================================================
-- PROFILES
-- =========================================================

create table if not exists profiles (
    id uuid primary key default gen_random_uuid(),
    full_name text not null,
    email text unique not null,
    role user_role not null,
    student_id text unique,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),

    constraint student_id_required_for_student
        check (
            role <> 'student'
            or student_id is not null
        )
);


-- =========================================================
-- CLASSES
-- =========================================================

create table if not exists classes (
    id uuid primary key default gen_random_uuid(),
    name text not null,
    code text unique not null,
    professor_id uuid not null references profiles(id) on delete restrict,
    room text not null,
    created_at timestamptz not null default now()
);


-- =========================================================
-- ENROLLMENTS
-- =========================================================

create table if not exists enrollments (
    id uuid primary key default gen_random_uuid(),
    class_id uuid not null references classes(id) on delete cascade,
    student_id uuid not null references profiles(id) on delete cascade,
    created_at timestamptz not null default now(),

    unique(class_id, student_id)
);


-- =========================================================
-- ATTENDANCE SESSIONS
-- =========================================================

create table if not exists attendance_sessions (
    id uuid primary key default gen_random_uuid(),
    class_id uuid not null references classes(id) on delete cascade,
    professor_id uuid not null references profiles(id) on delete restrict,
    room text not null,
    started_at timestamptz not null default now(),
    expires_at timestamptz not null,
    status session_status not null default 'active',
    created_at timestamptz not null default now(),

    constraint valid_session_window
        check (expires_at > started_at)
);


-- =========================================================
-- ROTATING QR TOKENS
-- =========================================================
--
-- Each token represents a short-lived QR generated by the server.
-- A token itself is NOT globally single-use.
-- Multiple students may redeem the same QR.
--
-- Per-student single-use is enforced by qr_token_redemptions
-- and the attendance_records unique(session_id, student_id)
-- constraint below.
--

create table if not exists qr_token_nonces (
    id uuid primary key default gen_random_uuid(),
    session_id uuid not null references attendance_sessions(id) on delete cascade,
    nonce_hash text not null,
    issued_at timestamptz not null default now(),
    expires_at timestamptz not null,

    unique(session_id, nonce_hash),

    constraint valid_qr_window
        check (expires_at > issued_at)
);


-- =========================================================
-- QR TOKEN REDEMPTIONS
-- =========================================================
--
-- Tracks which student redeemed which rotating QR token.
-- This prevents replay by the same student while allowing
-- other legitimate students to use the same QR.
--

create table if not exists qr_token_redemptions (
    id uuid primary key default gen_random_uuid(),
    session_id uuid not null references attendance_sessions(id) on delete cascade,
    student_id uuid not null references profiles(id) on delete cascade,
    nonce_hash text not null,
    redeemed_at timestamptz not null default now(),

    unique(session_id, student_id, nonce_hash)
);


-- =========================================================
-- DEVICE BINDINGS
-- =========================================================

create table if not exists device_bindings (
    id uuid primary key default gen_random_uuid(),
    student_id uuid not null references profiles(id) on delete cascade,
    device_id text not null,
    public_key text,
    status device_status not null default 'active',
    registered_at timestamptz not null default now(),
    last_seen_at timestamptz,

    unique(student_id),
    unique(device_id)
);


-- =========================================================
-- ATTENDANCE RECORDS
-- =========================================================

create table if not exists attendance_records (
    id uuid primary key default gen_random_uuid(),
    session_id uuid not null references attendance_sessions(id) on delete cascade,
    student_id uuid not null references profiles(id) on delete cascade,
    timestamp timestamptz not null default now(),

    qr_verified boolean not null default false,
    ble_verified boolean not null default false,
    biometric_verified boolean not null default false,
    device_verified boolean not null default false,

    status attendance_status not null default 'rejected',

    created_at timestamptz not null default now(),

    -- A student can have only one attendance result per session.
    unique(session_id, student_id)
);


-- =========================================================
-- SECURITY EVENTS
-- =========================================================

create table if not exists security_events (
    id uuid primary key default gen_random_uuid(),
    session_id uuid references attendance_sessions(id) on delete set null,
    student_id uuid references profiles(id) on delete set null,

    event_type text not null,
    reason text,
    metadata jsonb not null default '{}'::jsonb,

    created_at timestamptz not null default now()
);


-- =========================================================
-- INDEXES
-- =========================================================

create index if not exists idx_classes_professor
    on classes(professor_id);

create index if not exists idx_enrollments_student
    on enrollments(student_id);

create index if not exists idx_enrollments_class
    on enrollments(class_id);

create index if not exists idx_sessions_class
    on attendance_sessions(class_id);

create index if not exists idx_sessions_status
    on attendance_sessions(status);

create index if not exists idx_qr_nonces_session
    on qr_token_nonces(session_id);

create index if not exists idx_qr_redemptions_student
    on qr_token_redemptions(student_id);

create index if not exists idx_qr_redemptions_session
    on qr_token_redemptions(session_id);

create index if not exists idx_attendance_session
    on attendance_records(session_id);

create index if not exists idx_attendance_student
    on attendance_records(student_id);

create index if not exists idx_security_events_session
    on security_events(session_id);

create index if not exists idx_security_events_student
    on security_events(student_id);

create index if not exists idx_security_events_created
    on security_events(created_at desc);


