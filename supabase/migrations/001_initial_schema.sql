alter table device_bindings enable row level security;
alter table attendance_records enable row level security;
alter table security_events enable row level security;


-- =========================================================
-- PROFILE POLICIES
-- =========================================================

drop policy if exists "Users can read own profile" on profiles;

create policy "Users can read own profile"
on profiles
for select
using (auth.uid() = id);


-- =========================================================
-- ENROLLMENT POLICIES
-- =========================================================

drop policy if exists "Students can read own enrollments" on enrollments;

create policy "Students can read own enrollments"
on enrollments
for select
using (auth.uid() = student_id);


-- =========================================================
-- ATTENDANCE POLICIES
-- =========================================================

drop policy if exists "Students can read own attendance" on attendance_records;

create policy "Students can read own attendance"
on attendance_records
for select
using (auth.uid() = student_id);


-- =========================================================
-- DEVICE POLICIES
-- =========================================================

drop policy if exists "Students can read own device" on device_bindings;

create policy "Students can read own device"
on device_bindings
for select
using (auth.uid() = student_id);


